export function SocialIcon({ platform, ...props }: IconProps & { platform: SocialPlatform }) {
  const size = props.size ?? 16;
  switch (platform) {
    case "hackerrank":
      // HackerRank has no Lucide brand icon; a code glyph keeps the row consistent.
      return <Code2 {...props} size={size} />;
    case "eolymp":
      // Competitive-programming judge - a trophy reads closer than a code glyph.
      return <Trophy {...props} size={size} />;
    case "telegram":
      return <TelegramIcon {...props} size={size} />;
    case "youtube":
      return <YouTubeIcon {...props} size={size} />;
    case "github":
      return <GitHubIcon {...props} size={size} />;
    case "linkedin":
      return <LinkedInIcon {...props} size={size} />;
    case "x":
      return <XIcon {...props} size={size} />;
    case "scholar":
      return <GraduationCap {...props} size={size} />;
    case "orcid":
      return <IdCard {...props} size={size} />;
    case "email":
      return <Mail {...props} size={size} />;
  }
}
